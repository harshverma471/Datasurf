"""Generate the M1 test fixtures.

    .venv/bin/python data/fixtures/make_fixtures.py

Writes a deliberately awful workbook and a clean join target. Both outputs are committed
(see plans/folder-structure.md, the .gitignore fixture rule) so the evals stay reproducible
without shipping anyone's real data. Regenerate after changing what "messy" means here;
evals/test_ingest.py asserts against these exact values.

Every nasty trait is deliberate and listed in MESSY_TRAITS below.
"""

import random
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.utils import get_column_letter

HERE = Path(__file__).parent

MESSY_TRAITS = """
  rows 0-3     merged title banner, blank row, CONFIDENTIAL, blank row
  row 4        the real header
  order_date   raw Excel serial integers, not date-formatted cells
  revenue      strings carrying $ and thousands separators
  discount_pct blank in ~14% of rows, clustered in region=East
  duplicates   12 exact-duplicate rows
  last row     a TOTAL row mixed into the data
  sheet 2      "Notes" — junk, to prove the sheet picker
"""

HEADER = ["Order Date", "Region", "Rep ID", "Product", "Units", "Revenue ($)", "Discount %"]

REGIONS = ["North", "South", "East", "West"]
PRODUCTS = ["Atlas Pro", "Beacon", "Cirrus", "Delta One", "Ember"]

N_DATA_ROWS = 240
N_DUPES = 12
SERIAL_ORIGIN = 45231  # 2023-11-08 in Excel's 1900 system


def build_rows(rng: random.Random) -> list[list]:
    """The data rows, pre-mess. Revenue is already a string; dates are already serials."""
    rows = []
    for i in range(N_DATA_ROWS):
        region = rng.choice(REGIONS)
        revenue = round(rng.uniform(12.40, 98_430.00), 2)

        # discount is missing 14% of the time overall, but 90% of those blanks land in East.
        # This is what makes the Schema Card's clustered-missingness note non-trivial.
        blank = rng.random() < (0.55 if region == "East" else 0.02)
        discount = None if blank else round(rng.uniform(0.0, 0.45), 4)

        rows.append([
            SERIAL_ORIGIN + rng.randint(0, 420),      # serial int, NOT a date-formatted cell
            region,
            1001 + rng.randint(0, 246),
            rng.choice(PRODUCTS),
            rng.randint(1, 480),
            f"${revenue:,.2f}",                        # "$12,340.50"
            discount,
        ])

    rows.extend(rng.sample(rows, N_DUPES))             # exact duplicates, scattered by the shuffle
    rng.shuffle(rows)
    return rows


def write_messy_workbook(rows: list[list], path: Path) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Q1-Q4"

    ws["A1"] = "Acme Corp — Sales Export"
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(HEADER))
    ws["A3"] = "CONFIDENTIAL"
    # rows 2 and 4 stay empty on purpose — spacer rows the header detector must skip

    ws.append([])  # keeps the cursor honest before the explicit row writes below
    for col, name in enumerate(HEADER, start=1):
        ws.cell(row=5, column=col, value=name)         # 1-indexed row 5 == 0-indexed row 4

    for r, row in enumerate(rows, start=6):
        for c, value in enumerate(row, start=1):
            ws.cell(row=r, column=c, value=value)

    total_row = len(rows) + 6
    ws.cell(row=total_row, column=1, value="TOTAL")
    ws.cell(row=total_row, column=5, value=f"=SUM(E6:E{total_row - 1})")
    ws.cell(row=total_row, column=6, value="$1,204,370.00")

    for col in range(1, len(HEADER) + 1):
        ws.column_dimensions[get_column_letter(col)].width = 14

    notes = wb.create_sheet("Notes")
    notes["A1"] = "Export generated by the finance team"
    notes["A2"] = "Do not redistribute"

    wb.save(path)


def write_reps(rng: random.Random, path: Path) -> None:
    """Clean by design: the join target, and the input that proves the candidate-key note."""
    pd.DataFrame({
        "rep_id": range(1001, 1248),
        "rep_name": [f"Rep {i:04d}" for i in range(1001, 1248)],
        "territory": [rng.choice(REGIONS) for _ in range(247)],
    }).to_csv(path, index=False)


def main() -> None:
    rng = random.Random(20260929)  # seeded: the evals assert on exact counts

    rows = build_rows(rng)
    write_messy_workbook(rows, HERE / "messy_sales.xlsx")
    write_reps(rng, HERE / "reps.csv")

    print(f"wrote messy_sales.xlsx  ({len(rows)} data rows + 1 TOTAL row, 2 sheets)")
    print(f"wrote reps.csv          (247 rows)")
    print(MESSY_TRAITS)


if __name__ == "__main__":
    main()
